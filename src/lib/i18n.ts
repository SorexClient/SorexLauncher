function detectSystemLang(): Lang {
  try {
    const raw = (navigator.language || navigator.languages?.[0] || "en").toLowerCase();
    const short = raw.slice(0, 2) as Lang;
    return (dictionaries as any)[short] ? short : "en";
  } catch {
    return "en";
  }
}

function resolveInitialLang(): Lang {
  if (typeof localStorage === "undefined") return "en";
  const saved = localStorage.getItem("sorexclient_lang");
  if (saved === "auto" || !saved) return detectSystemLang();
  return (dictionaries as any)[saved] ? (saved as Lang) : detectSystemLang();
}

function resolveInitialPreference(): Lang | "auto" {
  if (typeof localStorage === "undefined") return "auto";
  const saved = localStorage.getItem("sorexclient_lang");
  return (saved as Lang | "auto") || "auto";
}

/** User's stored preference — can be "auto". */
export const languagePreference = writable<Lang | "auto">(resolveInitialPreference());

/** Resolved active language (never "auto"). */
export const currentLang = writable<Lang>(resolveInitialLang());

languagePreference.subscribe((pref) => {
  if (typeof localStorage === "undefined") return;
  localStorage.setItem("sorexclient_lang", pref);
  currentLang.set(pref === "auto" ? detectSystemLang() : pref);
});

/** Reactive translator. Usage in templates: {$t("home.welcomeBack")} */
export const t = derived(currentLang, ($lang) => {
  return (key: string): string =>
    dictionaries[$lang]?.[key] ?? dictionaries.en[key] ?? key;
});
